// Command eolgen refreshes eol_data.go, the operating system support dates
// that check UPD-004 uses, from endoflife.date. Run `go generate
// ./internal/checks` before each release; nobet itself never goes online.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"time"
)

// products maps nobet's keys (os-release IDs, plus centos-stream, which
// shares ID=centos) to endoflife.date products.
var products = []struct{ key, product string }{
	{"almalinux", "almalinux"},
	{"alpine", "alpine-linux"},
	{"amzn", "amazon-linux"},
	{"centos", "centos"},
	{"centos-stream", "centos-stream"},
	{"debian", "debian"},
	{"fedora", "fedora"},
	{"ol", "oracle-linux"},
	{"opensuse-leap", "opensuse"},
	{"rhel", "rhel"},
	{"rocky", "rocky-linux"},
	{"sles", "sles"},
	{"ubuntu", "ubuntu"},
}

type product struct {
	Result struct {
		Labels struct {
			EOES *string `json:"eoes"`
		} `json:"labels"`
		Releases []struct {
			Name string  `json:"name"`
			LTS  bool    `json:"isLts"`
			EOL  *string `json:"eolFrom"`
			EOES *string `json:"eoesFrom"`
		} `json:"releases"`
	} `json:"result"`
}

func main() {
	out := flag.String("o", "eol_data.go", "output file")
	flag.Parse()

	client := &http.Client{Timeout: 30 * time.Second}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by eolgen from endoflife.date; DO NOT EDIT.\n\npackage checks\n\n")
	fmt.Fprintf(&b, "// eolUpdated is when the support dates were fetched.\nconst eolUpdated = %q\n\n", time.Now().UTC().Format("2006-01-02"))
	fmt.Fprintf(&b, "var eolData = map[string]eolProduct{\n")
	for _, p := range products {
		data, err := fetch(client, p.product)
		if err != nil {
			log.Fatalf("%s: %v", p.product, err)
		}
		fmt.Fprintf(&b, "%q: {Extended: %q, Releases: []eolRelease{\n", p.key, str(data.Result.Labels.EOES))
		for _, r := range data.Result.Releases {
			fmt.Fprintf(&b, "{%q, %q, %q, %t},\n", r.Name, str(r.EOL), str(r.EOES), r.LTS)
		}
		fmt.Fprintf(&b, "}},\n")
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func fetch(c *http.Client, name string) (*product, error) {
	req, err := http.NewRequest("GET", "https://endoflife.date/api/v1/products/"+name+"/", nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "nobet-eolgen (https://github.com/olgacveysel/nobet)")
	resp, err := c.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("HTTP %s", resp.Status)
	}
	var p product
	if err := json.NewDecoder(resp.Body).Decode(&p); err != nil {
		return nil, err
	}
	if len(p.Result.Releases) == 0 {
		return nil, fmt.Errorf("no releases in the response")
	}
	return &p, nil
}

func str(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}
